function groupSites(rows: readonly SiteRow[]) {
  const result: Record<string, KantoEncounter[]> = {}
  for (const [site, level, members] of rows) {
    (result[site] ??= []).push(...members.map(speciesId => ({ speciesId, level, weight: 1 })))
  }
  return result
}

export const postgameVisitors = groupSites(visitorSites)
export const postgameRare: Record<string, LegendaryEncounter[]> = Object.fromEntries(
  Object.entries(groupSites(rareSites)).map(([site, members]) => [site, members.map(mon => ({ ...mon, championOnly: true }))]),
)
