const additions: Record<string, KantoEncounter[]> = Object.create(null)
function add(location: string, speciesId: string, level: number, weight: number) {
  (additions[location] ??= []).push({ speciesId, level, weight })
}
for (const [location, level, ...localSpecies] of habitats) {
  for (const speciesId of localSpecies) add(location, speciesId, level, 1)
}
for (const [location, from, to, ...localSpecies] of trainingHabitats) {
  const steps = Math.ceil((to - from) / 3)
  for (let i = 0; i <= steps; i++) {
    const level = from + Math.round((to - from) * i / steps)
    for (const speciesId of localSpecies) add(location, speciesId, level, 2 / (steps + 1))
  }
}
export const regionalHabitats: Readonly<Partial<Record<string, readonly KantoEncounter[]>>> = additions

// Draw 35% from locally added slots. Keep the original pool's relative odds,
// including weather, and give training species a fixed weight across their levels.
export function withRegionalHabitats(native: readonly KantoEncounter[], extra?: readonly KantoEncounter[], levelFloor = 1): readonly KantoEncounter[] {
  if (!extra?.length) return native
  const nativeMass = native.reduce((n, slot) => n + slot.weight, 0)
  const extraMass = extra.reduce((n, slot) => n + slot.weight, 0)
  const weightFactor = nativeMass ? nativeMass * 0.35 / (0.65 * extraMass) : 1
  return [...native, ...extra.map(slot => ({ ...slot, level: Math.max(levelFloor, slot.level), weight: slot.weight * weightFactor }))]
}
